export type Coordinate = [number, number]; // [longitude, latitude]

export type CourseProperties = {
  order?: number;
  name: string;
  feature_type: 'course_point' | 'route' | 'race_station' | 'km_split';
  role?: 'start' | 'finish' | 'checkpoint' | 'junction' | 'turnaround';
  plus_code?: string;
  description?: string;
  station_type?: 'water' | 'med' | 'uturn' | 'marshal';
  distance_km?: number;
  elevation_gain_m?: number;
  stroke?: string;
  'stroke-width'?: number;
  'stroke-opacity'?: number;
};

export type CourseFeature = {
  type: 'Feature';
  properties: CourseProperties;
  geometry:
    | { type: 'Point'; coordinates: Coordinate }
    | { type: 'LineString'; coordinates: Coordinate[] };
};

export type CourseGeoJson = {
  type: 'FeatureCollection';
  name: string;
  properties: {
    distance_km: number;
    elevation_gain_m?: number;
    generated?: string;
    coordinate_system?: string;
  };
  features: CourseFeature[];
};

export type SampledPoint = {
  lng: number;
  lat: number;
  distKm: number;
  elev: number;
};

export type RouteTelemetry = {
  totalKm: number;
  elevGain: number;
  minElev: number;
  maxElev: number;
  kmSplits: { km: number; coord: Coordinate; elev: number }[];
  sampled: SampledPoint[];
};

export type RouteOption = {
  id: string;
  shortLabel: string;
  title: string;
  distance: string;
  badge: '3K' | '5K' | '10K';
  description: string;
  turnaroundSummary: string;
  gunTime: string;
  color: string;
  file: string;
  kmlFile: string;
  gpxFile: string;
  googleMapsUrl: string;
  curvedCoords: [number, number][]; // [lng, lat] along Bohol Circumferential Road & Church pathways
};

