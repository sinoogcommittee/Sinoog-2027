// Haversine distance in kilometers
export function haversineDistance(c1: Coordinate, c2: Coordinate): number {
  const R = 6371.0;
  const lat1 = (c1[1] * Math.PI) / 180;
  const lon1 = (c1[0] * Math.PI) / 180;
  const lat2 = (c2[1] * Math.PI) / 180;
  const lon2 = (c2[0] * Math.PI) / 180;
  const dlat = lat2 - lat1;
  const dlon = lon2 - lon1;
  const a =
    Math.sin(dlat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dlon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

// Compute elevation estimate based on Guindulman coastal topography
export function estimateElevationMeters(coord: Coordinate): number {
  const [lng, lat] = coord;
  const distFromParish = haversineDistance(OFFICIAL_WAYPOINTS.PARISH_ARCH, coord);
  const baseElev = 18;
  const inlandFactor = Math.max(0, (lat - 9.730) * 120);
  const coastalUndulation = Math.sin(distFromParish * 2.8) * 4.5 + Math.cos(lng * 80) * 2.0;
  return Math.round(Math.max(8, Math.min(38, baseElev + inlandFactor + coastalUndulation)));
}

// Compute cumulative telemetry from curved road coordinates
export function computeRouteTelemetry(coords: Coordinate[]): RouteTelemetry {
  if (coords.length < 2) {
    return {
      totalKm: 0,
      elevGain: 0,
      minElev: 18,
      maxElev: 18,
      kmSplits: [],
      sampled: [],
    };
  }

  let runningDist = 0;
  let elevGain = 0;
  const sampled: SampledPoint[] = [
    {
      lng: coords[0][0],
      lat: coords[0][1],
      distKm: 0,
      elev: estimateElevationMeters(coords[0]),
    },
  ];

  let nextKmTarget = 1.0;
  const kmSplits: { km: number; coord: Coordinate; elev: number }[] = [];

  for (let i = 0; i < coords.length - 1; i++) {
    const c1 = coords[i];
    const c2 = coords[i + 1];
    const segmentKm = haversineDistance(c1, c2);
    runningDist += segmentKm;

    const e1 = sampled[sampled.length - 1].elev;
    const e2 = estimateElevationMeters(c2);
    if (e2 > e1) {
      elevGain += e2 - e1;
    }

    sampled.push({
      lng: c2[0],
      lat: c2[1],
      distKm: runningDist,
      elev: e2,
    });

    if (runningDist >= nextKmTarget) {
      kmSplits.push({
        km: Math.floor(runningDist),
        coord: c2,
        elev: e2,
      });
      nextKmTarget = Math.floor(runningDist) + 1.0;
    }
  }

  const elevations = sampled.map((s) => s.elev);
  const minElev = Math.min(...elevations);
  const maxElev = Math.max(...elevations);

  return {
    totalKm: runningDist,
    elevGain: Math.round(elevGain),
    minElev,
    maxElev,
    kmSplits,
    sampled,
  };
}

